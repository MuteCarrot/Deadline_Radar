"""
Deadline Radar - iCalendar (.ics) Export Module
Generates RFC 5545 compliant .ics calendar files with:
- Asia/Kolkata (IST) timezone awareness
- Separate handling for all-day deadlines (VALUE=DATE) and timed events
- Deterministic/stable UIDs across repeated exports to prevent calendar duplicates
- Excludes cancelled events
- Comprehensive rich descriptions containing source messages and audit trail
"""

import hashlib
from datetime import datetime, date, timedelta, time
from typing import List, Dict, Any, Optional
import pytz

try:
    from icalendar import Calendar, Event, Timezone, TimezoneStandard
    ICALENDAR_AVAILABLE = True
except ImportError:
    ICALENDAR_AVAILABLE = False

IST = pytz.timezone("Asia/Kolkata")


def generate_stable_uid(event: Dict[str, Any]) -> str:
    """Creates a deterministic, stable UID from event title and course."""
    key = f"{event.get('title', '')}-{event.get('course_or_subject', '')}-{event.get('date', '')}".encode("utf-8")
    hash_hex = hashlib.sha256(key).hexdigest()[:16]
    return f"dr-{hash_hex}@deadlineradar.local"


def escape_ics_text(text: Optional[str]) -> str:
    """Escapes characters according to RFC 5545."""
    if not text:
        return ""
    return (
        text.replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\r\n", "\\n")
        .replace("\n", "\\n")
    )


def export_to_ics(events: List[Dict[str, Any]], calendar_name: str = "Deadline Radar - Campus Schedule") -> str:
    """
    Exports a list of reconciled events into a valid .ics string.
    Only includes active, confirmed, or updated events (filters out cancelled).
    """
    now = datetime.now(pytz.utc)
    
    # Use icalendar library if installed
    if ICALENDAR_AVAILABLE:
        cal = Calendar()
        cal.add("prodid", "-//DeadlineRadar//Campus Deadline Radar 1.0//EN")
        cal.add("version", "2.0")
        cal.add("x-wr-calname", calendar_name)
        cal.add("x-wr-timezone", "Asia/Kolkata")
        
        for evt in events:
            # Exclude cancelled events and events without a valid date
            if evt.get("status") == "Cancelled" or not evt.get("date"):
                continue

            event_date = evt["date"]
            if isinstance(event_date, str):
                try:
                    event_date = datetime.strptime(event_date, "%Y-%m-%d").date()
                except ValueError:
                    continue

            vevent = Event()
            vevent.add("uid", generate_stable_uid(evt))
            vevent.add("dtstamp", now)
            vevent.add("summary", evt.get("title", "Campus Deadline"))

            # Build detailed description
            course = evt.get("course_or_subject") or "General"
            venue = evt.get("venue") or "Campus"
            audience = evt.get("audience") or "All"
            status = evt.get("status") or "Upcoming"
            
            src_lines = []
            for s in evt.get("source_details", []):
                src_lines.append(f"• [{s.get('sender', 'Sender')}] {s.get('text', '')}")
            
            audit_trail = "\n".join(src_lines) if src_lines else "None recorded"
            
            description = (
                f"Course/Subject: {course}\n"
                f"Status: {status}\n"
                f"Audience: {audience}\n"
                f"Venue: {venue}\n"
                f"Confidence: {int((evt.get('confidence') or 0.8) * 100)}%\n\n"
                f"--- SOURCE MESSAGES ---\n"
                f"{audit_trail}\n\n"
                f"Generated by Deadline Radar (IIIT Hyderabad AI Capstone)"
            )
            vevent.add("description", description)
            vevent.add("location", venue)

            time_str = evt.get("time")
            if time_str:
                # Timed event
                try:
                    parts = time_str.split(":")
                    hour = int(parts[0])
                    minute = int(parts[1]) if len(parts) > 1 else 0
                    
                    dt_start = IST.localize(datetime.combine(event_date, time(hour, minute)))
                    dt_end = dt_start + timedelta(hours=1)
                    
                    vevent.add("dtstart", dt_start)
                    vevent.add("dtend", dt_end)
                except Exception:
                    # Fallback to all-day if time parsing fails
                    vevent.add("dtstart", event_date)
            else:
                # All-day deadline / event
                vevent.add("dtstart", event_date)

            cal.add_component(vevent)

        return cal.to_ical().decode("utf-8")

    # RFC 5545 text fallback if icalendar library is not yet imported
    return build_rfc5545_string(events, now, calendar_name)


def build_rfc5545_string(events: List[Dict[str, Any]], now: datetime, calendar_name: str) -> str:
    """Deterministic fallback standard RFC 5545 generator."""
    dtstamp = now.strftime("%Y%m%dT%H%M%SZ")
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//DeadlineRadar//Campus Deadline Radar 1.0//EN",
        f"X-WR-CALNAME:{calendar_name}",
        "X-WR-TIMEZONE:Asia/Kolkata",
    ]

    for evt in events:
        if evt.get("status") == "Cancelled" or not evt.get("date"):
            continue

        event_date = evt["date"]
        if isinstance(event_date, str):
            try:
                event_date = datetime.strptime(event_date, "%Y-%m-%d").date()
            except ValueError:
                continue

        uid = generate_stable_uid(evt)
        lines.append("BEGIN:VEVENT")
        lines.append(f"UID:{uid}")
        lines.append(f"DTSTAMP:{dtstamp}")
        lines.append(f"SUMMARY:{escape_ics_text(evt.get('title', 'Campus Deadline'))}")
        lines.append(f"LOCATION:{escape_ics_text(evt.get('venue', 'Campus'))}")

        time_str = evt.get("time")
        if time_str:
            try:
                parts = time_str.split(":")
                hour = int(parts[0])
                minute = int(parts[1]) if len(parts) > 1 else 0
                start_dt = datetime.combine(event_date, time(hour, minute))
                end_dt = start_dt + timedelta(hours=1)
                lines.append(f"DTSTART;TZID=Asia/Kolkata:{start_dt.strftime('%Y%m%dT%H%M%S')}")
                lines.append(f"DTEND;TZID=Asia/Kolkata:{end_dt.strftime('%Y%m%dT%H%M%S')}")
            except Exception:
                lines.append(f"DTSTART;VALUE=DATE:{event_date.strftime('%Y%m%d')}")
        else:
            lines.append(f"DTSTART;VALUE=DATE:{event_date.strftime('%Y%m%d')}")

        desc = (
            f"Course: {evt.get('course_or_subject', 'General')} | "
            f"Status: {evt.get('status', 'Upcoming')} | "
            f"Audience: {evt.get('audience', 'All')}"
        )
        lines.append(f"DESCRIPTION:{escape_ics_text(desc)}")
        lines.append("END:VEVENT")

    lines.append("END:VCALENDAR")
    return "\r\n".join(lines)

